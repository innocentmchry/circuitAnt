"""Dynamically synthesized tools repository.

Persists tools generated by DynamicToolSynthesizer across sessions.
"""
from pathlib import Path
import importlib
import inspect
import types

HERE = Path(__file__).resolve().parent


def load_dynamic_tools(tools_instance) -> list[str]:
    """Loads all dynamically synthesized tools from this directory into the given Tools instance."""
    from agent.tools import Tools
    loaded = []
    for p in HERE.glob("*.py"):
        if p.name.startswith("_") or p.name == "__init__.py":
            continue
        mod_name = f"agent.dynamic_tools.{p.stem}"
        try:
            mod = importlib.import_module(mod_name)
            for name, obj in inspect.getmembers(mod, inspect.isfunction):
                if name == p.stem:
                    setattr(Tools, name, obj)
                    bound = types.MethodType(obj, tools_instance)
                    setattr(tools_instance, name, bound)
                    loaded.append(name)
        except Exception as exc:
            print(f"[WARNING] Failed to load dynamic tool {p.name}: {exc}")
    return loaded
